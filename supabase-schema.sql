-- تحديث المخزون تلقائيًا بعد حفظ تفاصيل الطلب.
create or replace function public.decrease_product_stock()
returns trigger language plpgsql security definer as $$
begin
  update public.products
  set stock = greatest(stock - new.quantity, 0), updated_at = now()
  where id = new.product_id;
  return new;
end;
$$;

drop trigger if exists order_item_decrease_stock on public.order_items;
create trigger order_item_decrease_stock
after insert on public.order_items
for each row execute function public.decrease_product_stock();


create table if not exists public.discount_coupons (
  id bigint generated by default as identity primary key,
  code text not null unique,
  discount_type text not null check (discount_type in ('percent','fixed')),
  discount_value numeric(10,2) not null check (discount_value > 0),
  active boolean not null default true,
  expires_at timestamptz,
  max_uses integer check (max_uses is null or max_uses > 0),
  uses_count integer not null default 0 check (uses_count >= 0),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);


alter table public.discount_coupons enable row level security;
drop policy if exists "public can read active coupons" on public.discount_coupons;
create policy "public can read active coupons" on public.discount_coupons for select using (active = true and (expires_at is null or expires_at > now()) and (max_uses is null or uses_count < max_uses));
drop policy if exists "admins manage coupons" on public.discount_coupons;
create policy "admins manage coupons" on public.discount_coupons for all to authenticated using (exists (select 1 from public.admin_users where user_id = auth.uid())) with check (exists (select 1 from public.admin_users where user_id = auth.uid()));

alter table public.orders add column if not exists coupon_code text;
create or replace function public.increment_coupon_usage()
returns trigger language plpgsql security definer as $$
begin
  if new.coupon_code is not null and new.coupon_code <> '' then
    update public.discount_coupons
    set uses_count = uses_count + 1, updated_at = now()
    where code = new.coupon_code and active = true
      and (expires_at is null or expires_at > now())
      and (max_uses is null or uses_count < max_uses);
  end if;
  return new;
end;
$$;
drop trigger if exists order_coupon_usage on public.orders;
create trigger order_coupon_usage after insert on public.orders
for each row execute function public.increment_coupon_usage();


create table if not exists public.site_visits (
  id bigint generated by default as identity primary key,
  visitor_id text not null,
  path text not null default '/',
  referrer text,
  user_agent text,
  visited_at timestamptz not null default now()
);
create index if not exists site_visits_visited_at_idx on public.site_visits (visited_at desc);
create index if not exists site_visits_visitor_id_idx on public.site_visits (visitor_id);
alter table public.site_visits enable row level security;

drop policy if exists "public can record visits" on public.site_visits;
create policy "public can record visits" on public.site_visits for insert with check (length(visitor_id) between 8 and 120);
drop policy if exists "admins read visits" on public.site_visits;
create policy "admins read visits" on public.site_visits for select to authenticated using (exists (select 1 from public.admin_users where user_id = auth.uid()));
