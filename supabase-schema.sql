create extension if not exists pgcrypto;

create table if not exists public.admin_users (
  user_id uuid primary key references auth.users(id) on delete cascade,
  role text not null default 'admin' check (role in ('admin')),
  created_at timestamptz not null default now()
);

create table if not exists public.products (
  id bigint generated by default as identity primary key,
  name text not null,
  type text not null check (type in ('تعليمية','تشاركية')),
  age text not null,
  skill text not null,
  price numeric(10,2) not null check (price >= 0),
  stock integer not null default 0 check (stock >= 0),
  description text not null default '',
  emoji text not null default '🧸',
  badge text not null default 'جديد',
  active boolean not null default true,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  image_url text,
  image_urls text[] not null default '{}'
);

create table if not exists public.orders (
  id uuid primary key default gen_random_uuid(),
  customer_name text not null,
  phone text not null,
  address text not null,
  city text not null,
  payment_method text not null check (payment_method in ('mada','apple','card','cod')),
  status text not null default 'pending' check (status in ('pending','confirmed','shipped','completed','cancelled')),
  total numeric(10,2) not null check (total >= 0),
  coupon_code text,
  created_at timestamptz not null default now()
);

create table if not exists public.order_items (
  id bigint generated by default as identity primary key,
  order_id uuid not null references public.orders(id) on delete cascade,
  product_id bigint references public.products(id) on delete set null,
  product_name text not null,
  quantity integer not null check (quantity > 0),
  unit_price numeric(10,2) not null check (unit_price >= 0)
);

alter table public.admin_users enable row level security;
alter table public.products enable row level security;
alter table public.orders enable row level security;
alter table public.order_items enable row level security;

-- لا تسمح للزائر بقراءة بيانات الطلبات. يمكنه فقط إنشاء طلب.
drop policy if exists "public can read active products" on public.products;
create policy "public can read active products" on public.products for select using (active = true);

drop policy if exists "public can create orders" on public.orders;
create policy "public can create orders" on public.orders for insert with check (true);

drop policy if exists "public can create order items" on public.order_items;
create policy "public can create order items" on public.order_items for insert with check (true);

-- المدير يستطيع إدارة كل البيانات بعد تسجيل الدخول.
drop policy if exists "admins can read own role" on public.admin_users;
create policy "admins can read own role" on public.admin_users for select to authenticated using (user_id = auth.uid());

drop policy if exists "admins manage products" on public.products;
create policy "admins manage products" on public.products for all to authenticated using (exists (select 1 from public.admin_users a where a.user_id = auth.uid())) with check (exists (select 1 from public.admin_users a where a.user_id = auth.uid()));

drop policy if exists "admins manage orders" on public.orders;
create policy "admins manage orders" on public.orders for all to authenticated using (exists (select 1 from public.admin_users a where a.user_id = auth.uid())) with check (exists (select 1 from public.admin_users a where a.user_id = auth.uid()));

drop policy if exists "admins manage order items" on public.order_items;
create policy "admins manage order items" on public.order_items for all to authenticated using (exists (select 1 from public.admin_users a where a.user_id = auth.uid())) with check (exists (select 1 from public.admin_users a where a.user_id = auth.uid()));

