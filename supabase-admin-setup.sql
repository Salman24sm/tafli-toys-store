-- إعداد متجر طفلي للألعاب في Supabase
-- شغّل هذا الملف من Supabase Dashboard → SQL Editor
-- لا تضع كلمة مرور أو service_role key في هذا الملف.

create extension if not exists pgcrypto;

create table if not exists public.admin_users (
  user_id uuid primary key references auth.users(id) on delete cascade,
  role text not null default 'admin',
  created_at timestamptz not null default now()
);

create table if not exists public.products (
  id bigint generated by default as identity primary key,
  name text not null,
  type text not null,
  age text not null,
  skill text not null,
  price numeric(10,2) not null check (price >= 0),
  stock integer not null default 0 check (stock >= 0),
  description text not null default '',
  emoji text not null default '🧸',
  badge text not null default 'جديد',
  active boolean not null default true,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.orders (
  id uuid primary key default gen_random_uuid(),
  customer_name text not null,
  phone text not null,
  address text not null,
  city text not null,
  payment_method text not null,
  status text not null default 'awaiting_payment',
  total numeric(10,2) not null check (total >= 0),
  payment_id text unique,
  payment_status text,
  paid_at timestamptz,
  created_at timestamptz not null default now()
);

create table if not exists public.order_items (
  id bigint generated by default as identity primary key,
  order_id uuid not null references public.orders(id) on delete cascade,
  product_id bigint references public.products(id) on delete set null,
  product_name text not null,
  quantity integer not null check (quantity > 0),
  unit_price numeric(10,2) not null check (unit_price >= 0)
);

alter table public.admin_users enable row level security;
alter table public.products enable row level security;
alter table public.orders enable row level security;
alter table public.order_items enable row level security;

-- سياسات القراءة العامة للمنتجات النشطة
 drop policy if exists "public reads active products" on public.products;
create policy "public reads active products"
on public.products for select
using (active = true);

-- سياسات المدير
 drop policy if exists "admin reads own role" on public.admin_users;
create policy "admin reads own role"
on public.admin_users for select to authenticated
using (user_id = auth.uid());

 drop policy if exists "admins manage products" on public.products;
create policy "admins manage products"
on public.products for all to authenticated
using (exists (select 1 from public.admin_users where user_id = auth.uid()))
with check (exists (select 1 from public.admin_users where user_id = auth.uid()));

 drop policy if exists "admins manage orders" on public.orders;
create policy "admins manage orders"
on public.orders for all to authenticated
using (exists (select 1 from public.admin_users where user_id = auth.uid()))
with check (exists (select 1 from public.admin_users where user_id = auth.uid()));

 drop policy if exists "admins manage order items" on public.order_items;
create policy "admins manage order items"
on public.order_items for all to authenticated
using (exists (select 1 from public.admin_users where user_id = auth.uid()))
with check (exists (select 1 from public.admin_users where user_id = auth.uid()));

